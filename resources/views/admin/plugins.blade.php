        <script>
            /* Admin plugins: hide/show a plugin, delete with a second tap. (Search is in ui.js.) */
            (function () {
                "use strict";
                document.getElementById("pluginRows").addEventListener("click", function (e) {
                    var toggle = e.target.closest("[data-toggle]");
                    if (toggle) {
                        // DEMO: Laravel saves the new status.
                        var row = toggle.closest("tr");
                        var badge = row.querySelector(".badge");
                        var hide = toggle.textContent.trim() === "Hide";
                        badge.textContent = hide ? "Hidden" : "Live";
                        badge.classList.toggle("ok", !hide);
                        toggle.textContent = hide ? "Show" : "Hide";
                        Toon.toast(hide ? "Plugin hidden from customers" : "Plugin is live");
                        return;
                    }
                    var del = e.target.closest("[data-del]");
                    if (del && Toon.armed(del, "Sure?")) {
                        // DEMO: Laravel deletes the plugin.
                        del.closest("tr").remove();
                        Toon.toast("Plugin deleted");
                    }
                });
            })();
        </script>
